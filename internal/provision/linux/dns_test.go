func TestReconcileGuestDNSSanitizesAndRestartsDnsmasq(t *testing.T) {
	conf := "listen-address=192.168.5.1\nbind-interfaces\naddress=/host.docker.internal/192.168.5.2\n"
	resolv := "# Generated by Colima\nnameserver 192.168.5.1\n"
	backend := dnsInspectionBackend(presentDNSInspection(conf, resolv, true))

	result, err := ReconcileGuestDNS("dev", backend, nil)
	if err != nil {
		t.Fatalf("ReconcileGuestDNS() error = %v", err)
	}
	if !result.ConfigChanged || !result.ResolvConfChanged || !result.ServiceRestarted {
		t.Fatalf("result = %#v, want both files repaired and dnsmasq restarted", result)
	}
	if len(backend.SSHScriptCalls) != 2 {
		t.Fatalf("guest calls = %d, want inspection and one repair", len(backend.SSHScriptCalls))
	}
	repair := backend.SSHScriptCalls[1].Script
	wantResolv := renderResolvConf("192.168.5.3", "192.168.5.2")
	wantDnsmasq := "address=/host.docker.internal/192.168.5.2\nlocal-service\n"
	if got := repairWritePayload(t, repair, guestResolvConfPath); got != wantResolv {
		t.Errorf("resolv.conf payload = %q, want %q", got, wantResolv)
	}
	if got := repairWritePayload(t, repair, colimaDnsmasqConfPath); got != wantDnsmasq {
		t.Errorf("dnsmasq payload = %q, want %q", got, wantDnsmasq)
	}
	assertRepairOperationOrder(t, repair, guestResolvConfPath, colimaDnsmasqConfPath, "timeout --kill-after=2s 15s systemctl restart dnsmasq")
	for _, want := range []string{"set -euo pipefail", "chmod 0644", "timeout --kill-after=2s 15s systemctl restart dnsmasq", "timeout --kill-after=2s 5s systemctl is-active --quiet dnsmasq"} {
		if !strings.Contains(repair, want) {
			t.Errorf("repair script does not contain %q:\n%s", want, repair)
		}
	}
}

