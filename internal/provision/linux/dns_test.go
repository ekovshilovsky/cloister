func presentDNSInspection(conf, resolv string, active bool) string {
	return dnsInspection(conf, resolv, true, active, "192.168.5.2", false)
}

func dnsInspection(conf, resolv string, resolvPresent, active bool, gateway string, serviceCheckTimedOut bool) string {
	return dnsInspectionWithDanglingResolv(conf, resolv, resolvPresent, active, gateway, serviceCheckTimedOut, false)
}

func dnsInspectionWithDanglingResolv(conf, resolv string, resolvPresent, active bool, gateway string, serviceCheckTimedOut, resolvDangling bool) string {
	service := "0"
	if active {
		service = "1"
	}
	serviceTimeout := "0"
	if serviceCheckTimedOut {
		serviceTimeout = "1"
	}
	present := "0"
	if resolvPresent {
		present = "1"
	}
	dangling := "0"
	if resolvDangling {
		dangling = "1"
	}
	return guestDNSInspectMarker + "\n" +
		"state=present\n" +
		"guest_ipv4=192.168.5.3\n" +
		"gateway_ipv4=" + gateway + "\n" +
		"service_active=" + service + "\n" +
		"service_check_timeout=" + serviceTimeout + "\n" +
		"dnsmasq_conf=" + base64.StdEncoding.EncodeToString([]byte(conf)) + "\n" +
		"resolv_present=" + present + "\n" +
		"resolv_dangling_symlink=" + dangling + "\n" +
		"resolv_conf=" + base64.StdEncoding.EncodeToString([]byte(resolv)) + "\n"
}

func repairWritePayload(t *testing.T, script, path string) string {
	t.Helper()
	pathAt := strings.Index(script, path)
	if pathAt < 0 {
		t.Fatalf("repair script has no write for %s:\n%s", path, script)
	}
	for _, line := range strings.Split(script[pathAt:], "\n") {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "if ! printf ") || !strings.Contains(trimmed, " | base64 --decode") {
			continue
		}
		fields := strings.Fields(trimmed)
		if len(fields) < 7 {
			t.Fatalf("could not parse payload write for %s: %q", path, line)
		}
		decoded, err := base64.StdEncoding.DecodeString(fields[4])
		if err != nil {
			t.Fatalf("decode payload for %s: %v", path, err)
		}
		return string(decoded)
	}
	t.Fatalf("repair script has no payload for %s:\n%s", path, script)
	return ""
}

func assertRepairOperationOrder(t *testing.T, script string, operations ...string) {
	t.Helper()
	previous := -1
	for _, operation := range operations {
		index := strings.Index(script, operation)
		if index < 0 {
			t.Fatalf("repair script has no %q operation:\n%s", operation, script)
		}
		if index <= previous {
			t.Fatalf("repair operation %q is out of order in:\n%s", operation, script)
		}
		previous = index
	}
}
