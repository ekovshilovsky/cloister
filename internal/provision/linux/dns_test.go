func TestSanitizeDnsmasqConf(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		input string
		want  string
	}{
		{
			name: "removes stale binding directives and preserves resolver rules",
			input: "# Generated by Colima\n" +
				"listen-address=192.168.5.1\n" +
				"bind-interfaces\n" +
				"bind-dynamic\n" +
				"interface=eth0\n" +
				"address=/host.docker.internal/192.168.5.2\n" +
				"server=192.168.5.2\n" +
				"# retain this comment\n",
			want: "# Generated by Colima\n" +
				"address=/host.docker.internal/192.168.5.2\n" +
				"server=192.168.5.2\n" +
				"# retain this comment\n" +
				"local-service\n",
		},
		{
			name:  "preserves already sanitized input byte for byte",
			input: "address=/host.docker.internal/192.168.5.2\r\nserver=192.168.5.2\r\nlocal-service",
			want:  "address=/host.docker.internal/192.168.5.2\r\nserver=192.168.5.2\r\nlocal-service",
		},
		{
			name:  "does not treat commented directives as active",
			input: "# listen-address=192.168.5.1\n# bind-interfaces\n",
			want:  "# listen-address=192.168.5.1\n# bind-interfaces\nlocal-service\n",
		},
		{
			name:  "keeps existing local service directive idempotent",
			input: "address=/host.docker.internal/192.168.5.2\nlocal-service\nserver=192.168.5.2\n",
			want:  "address=/host.docker.internal/192.168.5.2\nlocal-service\nserver=192.168.5.2\n",
		},
		{
			name:  "keeps local service host directive idempotent",
			input: "address=/host.docker.internal/192.168.5.2\nlocal-service=host\n",
			want:  "address=/host.docker.internal/192.168.5.2\nlocal-service=host\n",
		},
		{
			name:  "terminates local service in an otherwise empty config",
			input: "",
			want:  "local-service\n",
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			if got := sanitizeDnsmasqConf(test.input); got != test.want {
				t.Errorf("sanitizeDnsmasqConf() = %q, want %q", got, test.want)
			}
		})
	}
}

